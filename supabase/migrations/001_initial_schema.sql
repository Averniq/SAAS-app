create or replace function public.create_restaurant_for_owner(
  p_name text, p_restaurant_type text, p_phone text, p_address text,
  p_logo_url text default '', p_timezone text default 'Australia/Sydney'
) returns jsonb language plpgsql security definer set search_path = public as $$
declare target_id uuid; target_slug text; base_slug text;
begin
  if auth.uid() is null then raise exception 'AUTH_REQUIRED'; end if;
  if exists(select 1 from public.restaurant_staff where user_id = auth.uid() and role = 'owner') then
    raise exception 'OWNER_RESTAURANT_ALREADY_EXISTS';
  end if;
  if length(trim(coalesce(p_name,''))) < 2 then raise exception 'INVALID_RESTAURANT_NAME'; end if;
  base_slug := trim(both '-' from regexp_replace(lower(unaccent(p_name)),'[^a-z0-9]+','-','g'));
  if base_slug = '' then base_slug := 'restaurant'; end if;
  target_slug := base_slug;
  while exists(select 1 from public.restaurants where slug = target_slug) loop
    target_slug := base_slug || '-' || substr(replace(gen_random_uuid()::text,'-',''),1,5);
  end loop;
  insert into public.restaurants(owner_user_id,name,slug,restaurant_type,phone,address,logo_url,timezone,status)
  values(auth.uid(),trim(p_name),target_slug,trim(coalesce(p_restaurant_type,'')),trim(coalesce(p_phone,'')),
    trim(coalesce(p_address,'')),trim(coalesce(p_logo_url,'')),coalesce(nullif(trim(p_timezone),''),'Australia/Sydney'),'onboarding')
  returning id into target_id;
  insert into public.restaurant_staff(restaurant_id,user_id,role) values(target_id,auth.uid(),'owner');
  return jsonb_build_object('id',target_id,'slug',target_slug,'name',trim(p_name));
end;
$$;

create or replace function public.create_restaurant_tables(p_restaurant_id uuid,p_count integer)
returns integer language plpgsql security definer set search_path = public as $$
begin
  if not public.has_restaurant_role(p_restaurant_id,array['owner','manager']) then raise exception 'ACCESS_DENIED'; end if;
  if p_count not between 1 and 100 then raise exception 'TABLE_COUNT_OUT_OF_RANGE'; end if;
  insert into public.tables(restaurant_id,local_id,table_number,table_name,name,table_token,sort_order)
  select p_restaurant_id,'table-'||n,n,'Table '||n,'Table '||n,
    'tk_'||upper(substr(replace(gen_random_uuid()::text,'-',''),1,10)),n
  from generate_series(1,p_count) n on conflict (restaurant_id,local_id) do nothing;
  return p_count;
end;
$$;

create or replace function public.get_public_restaurant(p_slug text,p_table_ref text)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare result jsonb;
begin
  select jsonb_build_object(
    'restaurant',jsonb_build_object('id',r.id,'slug',r.slug,'name',r.name,'subtitle',r.subtitle,'address',r.address,
      'phone',r.phone,'tax_rate',r.tax_rate,'is_open',r.is_open,'logo_url',r.logo_url,'theme_config',r.theme_config,'timezone',r.timezone),
    'tables',(select coalesce(jsonb_agg(jsonb_build_object('id',t.id,'local_id',t.local_id,'table_number',t.table_number,
      'table_name',t.table_name,'table_token',t.table_token,'sort_order',t.sort_order) order by t.sort_order),'[]'::jsonb)
      from public.tables t where t.restaurant_id=r.id and t.is_active and
        ((coalesce(p_table_ref,'')<>'' and (t.local_id=p_table_ref or t.table_token=p_table_ref)) or
         (coalesce(p_table_ref,'')='' and public.is_restaurant_staff(r.id)))),
    'menu_items',(select coalesce(jsonb_agg(jsonb_build_object('id',m.id,'local_id',m.local_id,'category_id',m.category_id,
      'category',coalesce(c.name,m.category),'name',m.name,'description',m.description,'price',m.price,'tags',m.tags,
      'image_url',coalesce(nullif(m.image_url,''),m.photo_url),'option_template',m.option_template,
      'is_available',m.is_available and m.is_active and not m.sold_out,'sort_order',m.sort_order) order by c.sort_order,m.sort_order),'[]'::jsonb)
      from public.menu_items m left join public.categories c on c.id=m.category_id
      where m.restaurant_id=r.id and m.is_active and (c.is_active is null or c.is_active))
  ) into result from public.restaurants r
  where r.slug=p_slug and r.status in ('active','onboarding') and r.is_active;
  if result is null then raise exception 'RESTAURANT_NOT_FOUND'; end if;
  if coalesce(p_table_ref,'')<>'' and jsonb_array_length(result->'tables')<>1 then raise exception 'TABLE_NOT_FOUND'; end if;
  return result;
end;
$$;

create or replace function public.submit_order(
  p_restaurant_id uuid,p_table_id uuid,p_local_id text,p_note text,p_items jsonb,p_customer_name text default ''
) returns jsonb language plpgsql security definer set search_path = public as $$
declare target_order_id uuid; target_order_number bigint; target_tax_rate numeric(5,2);
  calculated_subtotal numeric(10,2); calculated_tax numeric(10,2); calculated_total numeric(10,2);
begin
  if length(trim(coalesce(p_local_id,'')))<3 then raise exception 'INVALID_ORDER_ID'; end if;
  if jsonb_typeof(p_items)<>'array' or jsonb_array_length(p_items) not between 1 and 50 then raise exception 'INVALID_ORDER_ITEMS'; end if;
  select r.tax_rate into target_tax_rate from public.restaurants r join public.tables t on t.restaurant_id=r.id
  where r.id=p_restaurant_id and r.status in ('active','onboarding') and r.is_open and t.id=p_table_id and t.is_active;
  if target_tax_rate is null then raise exception 'INVALID_OR_CLOSED_TABLE'; end if;
  select id,order_number into target_order_id,target_order_number from public.orders
    where restaurant_id=p_restaurant_id and local_id=p_local_id limit 1;
  if target_order_id is not null then return jsonb_build_object('id',target_order_id,'order_number',target_order_number); end if;
  if exists(select 1 from jsonb_array_elements(p_items) i where coalesce((i->>'quantity')::integer,0) not between 1 and 99
    or not exists(select 1 from public.menu_items m where m.id=nullif(i->>'menu_item_id','')::uuid
      and m.restaurant_id=p_restaurant_id and m.is_active and m.is_available and not m.sold_out)) then
    raise exception 'INVALID_ORDER_ITEM';
  end if;
  select round(sum(m.price*(i->>'quantity')::integer),2) into calculated_total
    from jsonb_array_elements(p_items) i join public.menu_items m on m.id=(i->>'menu_item_id')::uuid
    where m.restaurant_id=p_restaurant_id;
  calculated_tax:=round(calculated_total*target_tax_rate/(100+target_tax_rate),2);
  calculated_subtotal:=calculated_total-calculated_tax;
  insert into public.orders(restaurant_id,table_id,local_id,customer_name,status,note,subtotal,tax,total)
  values(p_restaurant_id,p_table_id,p_local_id,left(coalesce(p_customer_name,''),120),'new',left(coalesce(p_note,''),1000),calculated_subtotal,calculated_tax,calculated_total)
  returning id,order_number into target_order_id,target_order_number;
  insert into public.order_items(restaurant_id,order_id,menu_item_id,item_name,name_snapshot,quantity,price,base_price,unit_price,notes,options)
  select p_restaurant_id,target_order_id,m.id,m.name,m.name,(i->>'quantity')::integer,m.price,m.price,m.price,
    left(coalesce(i->>'notes',''),500),coalesce(i->'options','[]'::jsonb)
  from jsonb_array_elements(p_items) i join public.menu_items m on m.id=(i->>'menu_item_id')::uuid
  where m.restaurant_id=p_restaurant_id;
  return jsonb_build_object('id',target_order_id,'order_number',target_order_number);
end;
$$;

create or replace function public.get_customer_order_status(p_order_id uuid,p_local_id text,p_table_token text)
returns jsonb language sql stable security definer set search_path = public as $$
  select jsonb_build_object('id',o.id,'local_id',o.local_id,'order_number',o.order_number,'status',o.status,
    'total',o.total,'created_at',o.created_at,'served_at',o.served_at,'closed_at',o.closed_at,
    'updated_at',o.updated_at,'table_name',t.table_name)
  from public.orders o join public.tables t on t.id=o.table_id and t.restaurant_id=o.restaurant_id
  where o.id=p_order_id and o.local_id=p_local_id and t.table_token=p_table_token and t.is_active
    and o.created_at>now()-interval '24 hours' limit 1;
$$;

