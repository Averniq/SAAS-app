-- Aveniq SaaS V1 standalone database.
-- Run only in a NEW, empty Supabase project created for Aveniq.

create extension if not exists pgcrypto;
create extension if not exists unaccent;

create table public.restaurants (
  id uuid primary key default gen_random_uuid(),
  owner_user_id uuid references auth.users(id) on delete set null,
  name text not null,
  slug text not null unique,
  restaurant_type text not null default '',
  logo_url text not null default '',
  address text not null default '',
  phone text not null default '',
  timezone text not null default 'Australia/Sydney',
  status text not null default 'onboarding' check (status in ('onboarding','active','suspended','inactive')),
  subtitle text not null default 'QR table ordering',
  tax_id text not null default '',
  tax_rate numeric(5,2) not null default 10 check (tax_rate between 0 and 30),
  is_open boolean not null default true,
  is_active boolean not null default true,
  theme_config jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.restaurant_staff (
  id uuid primary key default gen_random_uuid(),
  restaurant_id uuid not null references public.restaurants(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'cashier' check (role in ('owner','manager','kitchen','cashier')),
  created_at timestamptz not null default now(),
  unique (restaurant_id, user_id)
);

create table public.categories (
  id uuid primary key default gen_random_uuid(),
  restaurant_id uuid not null references public.restaurants(id) on delete cascade,
  name text not null,
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (restaurant_id, name)
);

create table public.tables (
  id uuid primary key default gen_random_uuid(),
  restaurant_id uuid not null references public.restaurants(id) on delete cascade,
  table_number integer,
  table_name text not null,
  qr_code_url text not null default '',
  local_id text not null,
  name text not null,
  table_token text not null unique,
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (restaurant_id, local_id),
  unique (restaurant_id, table_number)
);

create table public.menu_items (
  id uuid primary key default gen_random_uuid(),
  restaurant_id uuid not null references public.restaurants(id) on delete cascade,
  category_id uuid references public.categories(id) on delete set null,
  name text not null,
  description text not null default '',
  price numeric(10,2) not null check (price >= 0),
  image_url text not null default '',
  is_available boolean not null default true,
  sort_order integer not null default 0,
  local_id text not null,
  category text not null,
  tags jsonb not null default '[]'::jsonb,
  photo_url text not null default '',
  option_template text not null default 'none',
  sold_out boolean not null default false,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (restaurant_id, local_id)
);

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  restaurant_id uuid not null references public.restaurants(id) on delete restrict,
  table_id uuid not null references public.tables(id) on delete restrict,
  order_number bigint generated by default as identity,
  customer_name text not null default '',
  status text not null default 'new' check (status in ('new','preparing','ready','completed','cancelled')),
  subtotal numeric(10,2) not null default 0,
  total numeric(10,2) not null default 0,
  local_id text,
  public_token uuid not null default gen_random_uuid() unique,
  note text not null default '',
  tax numeric(10,2) not null default 0,
  created_at timestamptz not null default now(),
  served_at timestamptz,
  closed_at timestamptz,
  updated_at timestamptz not null default now()
);

create table public.order_items (
  id uuid primary key default gen_random_uuid(),
  restaurant_id uuid not null references public.restaurants(id) on delete restrict,
  order_id uuid not null references public.orders(id) on delete cascade,
  menu_item_id uuid references public.menu_items(id) on delete set null,
  item_name text not null,
  quantity integer not null check (quantity between 1 and 99),
  price numeric(10,2) not null check (price >= 0),
  notes text not null default '',
  name_snapshot text not null,
  base_price numeric(10,2) not null default 0,
  unit_price numeric(10,2) not null default 0,
  options jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

create index restaurant_staff_user_idx on public.restaurant_staff(user_id, restaurant_id);
create index categories_restaurant_sort_idx on public.categories(restaurant_id, sort_order);
create index tables_restaurant_active_idx on public.tables(restaurant_id, is_active, sort_order);
create index menu_items_restaurant_category_idx on public.menu_items(restaurant_id, category_id, sort_order);
create index orders_restaurant_status_created_idx on public.orders(restaurant_id, status, created_at desc);
create unique index orders_restaurant_local_unique on public.orders(restaurant_id, local_id) where local_id is not null;
create index order_items_restaurant_order_idx on public.order_items(restaurant_id, order_id);

create or replace function public.set_updated_at()
returns trigger language plpgsql set search_path = public as $$
begin new.updated_at = now(); return new; end;
$$;

create trigger restaurants_updated_at before update on public.restaurants
for each row execute function public.set_updated_at();
create trigger tables_updated_at before update on public.tables
for each row execute function public.set_updated_at();
create trigger menu_items_updated_at before update on public.menu_items
for each row execute function public.set_updated_at();
create trigger orders_updated_at before update on public.orders
for each row execute function public.set_updated_at();

create or replace function public.is_restaurant_staff(target_restaurant uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select exists(select 1 from public.restaurant_staff
    where restaurant_id = target_restaurant and user_id = auth.uid());
$$;

create or replace function public.has_restaurant_role(target_restaurant uuid, allowed_roles text[])
returns boolean language sql stable security definer set search_path = public as $$
  select exists(select 1 from public.restaurant_staff
    where restaurant_id = target_restaurant and user_id = auth.uid() and role = any(allowed_roles));
$$;

revoke all on function public.is_restaurant_staff(uuid) from public;
revoke all on function public.has_restaurant_role(uuid,text[]) from public;
grant execute on function public.is_restaurant_staff(uuid), public.has_restaurant_role(uuid,text[]) to authenticated;

